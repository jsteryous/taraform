    and m.client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid());
$$;

revoke execute on function public.sms_unread_count(uuid) from public, anon;
grant execute on function public.sms_unread_count(uuid) to authenticated;

-- Marking read is a write to sms_messages, which members cannot write directly (every other
-- write goes through a SECURITY DEFINER function for the same reason). Membership-gated:
-- ids from another tenant are silently not updated rather than erroring, because the caller
-- has no business learning whether they exist.
create or replace function public.sms_mark_read(p_ids bigint[])
returns int
language plpgsql security definer set search_path to 'public'
as $$
declare v_n int;
begin
  update public.sms_messages m
  set read_at = now()
  where m.id = any(coalesce(p_ids, '{}'::bigint[]))
    and m.direction = 'inbound'
    and m.read_at is null
    and m.client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid());
  get diagnostics v_n = row_count;
  return v_n;
end;
$$;

revoke execute on function public.sms_mark_read(bigint[]) from public, anon;
grant execute on function public.sms_mark_read(bigint[]) to authenticated;

-- Marks every inbound message from one number read, across contacts. The thread view uses
-- this: the operator read the conversation, not a list of row ids, and a number shared by
-- four contacts should not stay "unread" on three of them.
create or replace function public.sms_mark_thread_read(p_phone text)
returns int
language plpgsql security definer set search_path to 'public'
as $$
declare v_n int;
begin
  update public.sms_messages m
  set read_at = now()
  where m.peer_number = public.sms_digits(p_phone)
    and m.direction = 'inbound'
    and m.read_at is null
    and m.client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid());
  get diagnostics v_n = row_count;
  return v_n;
end;
$$;

revoke execute on function public.sms_mark_thread_read(text) from public, anon;
grant execute on function public.sms_mark_thread_read(text) to authenticated;

