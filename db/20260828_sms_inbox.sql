-- ── 6. The HELP auto-reply's write path ────────────────────────────────────────
-- This cannot go through sms_record_outbound(): that function demands a member user id and
-- raises without one, which is right for a human send and wrong for a machine one. This is
-- the only outbound path with sent_by null, which is also how the once-per-day guard in
-- sms_record_inbound() recognises an auto-reply.
--
-- service_role only. Called from sms-inbound — the one publicly reachable function — and
-- only after that function has verified the Telnyx Ed25519 signature.
create or replace function public.sms_record_help_reply(
  p_peer text, p_from text, p_body text, p_sid text
)
returns bigint
language plpgsql security definer set search_path to 'public'
as $$
declare v_id bigint; v_client uuid; v_peer text := public.sms_digits(p_peer);
begin
  select cl.id into v_client from public.clients cl
  where public.sms_digits(cl.sms_number) = public.sms_digits(p_from) limit 1;
  if v_client is null then return null; end if;

  -- Belt and braces: never auto-reply into a suppressed number even if the caller asked.
  if exists (select 1 from public.sms_opt_outs o where o.phone = v_peer) then return null; end if;

  insert into public.sms_messages (
    client_id, contact_id, direction, peer_number, from_number, to_number,
    body, provider_sid, status, sent_by
  )
  select v_client,
         (select c.id from public.property_crm_contacts c
          where c.client_id = v_client
            and exists (select 1 from jsonb_array_elements_text(coalesce(c.phones,'[]'::jsonb)) p
                        where public.sms_digits(p) = v_peer)
          order by c.updated_at desc nulls last limit 1),
         'outbound', v_peer, public.sms_digits(p_from), v_peer,
         p_body, p_sid, 'sent', null
  on conflict (provider_sid) do nothing
  returning id into v_id;

  return v_id;
end;
$$;

revoke execute on function public.sms_record_help_reply(text, text, text, text) from public, anon, authenticated;

-- ── 7. Re-revoke sms_record_inbound ────────────────────────────────────────────
-- DROP FUNCTION + CREATE re-grants EXECUTE to PUBLIC by default, which silently undid the
-- revoke from db/20260827_sms.sql. sms_record_inbound writes opt-outs and inserts into
-- sms_messages as SECURITY DEFINER; reachable by anon it would let anyone holding the
-- public bundle's key forge a reply into a tenant's thread, or forge a STOP.
--
-- Generalisable lesson, and the second of its kind in this codebase (see the "TO public"
-- note in the Tier 1 backlog): REPLACING a function preserves its grants, RECREATING it
-- does not. Any migration that drops and recreates a SECURITY DEFINER function must
-- re-issue the revoke, and should be checked with has_function_privilege afterwards.
revoke execute on function public.sms_record_inbound(text, text, text, text) from public, anon, authenticated;

commit;

-- ── Verification ───────────────────────────────────────────────────────────────
-- STOP corpus. Run after any edit to sms_is_stop(); it must return zero rows. The false
-- positives at the bottom are the ones that actually threaten this business: "stop by the
-- property" is a sentence land owners really send.
--
-- with cases(body, want) as (values
--   ('STOP', true), ('Stop.', true), ('STOP ALL', true), ('unsubscribe', true),
--   ('please stop.', true), ('ok stop', true), ('stop it', true),
--   ('please stop texting me', true), ('quit texting me', true),
--   ('remove me', true), ('Remove me from your list', true),
--   ('take my number off your list', true), ('take me off', true),
--   ('delete my number', true), ('do not text me', true), ('dont contact me', true),
--   ('don''t text me again', true), ('never contact me again', true),
--   ('no more texts', true), ('leave me alone', true), ('lose my number', true),
--   ('wrong number', true), ('Wrong #', true), ('not interested', true),
--   ('stop bothering me', true), ('opt me out please', true), ('cancel', true),
--   ('You can stop by the property any time', false),
--   ('Feel free to stop by this weekend', false),
--   ('I will stop over tomorrow to look at it', false),
--   ('Yes I am interested', false), ('How much are you offering?', false),
--   ('Call me at 8am', false), ('I already sold it', false),
--   ('Sure, send me the info', false), ('That is the wrong parcel number', false)
-- )
-- select body, want, public.sms_is_stop(body) as got
-- from cases where public.sms_is_stop(body) <> want;
--
-- Grants. Every write-path function must be service_role only; anon must reach nothing.
--
-- select p.proname,
--        has_function_privilege('anon', p.oid, 'EXECUTE') as anon,
--        has_function_privilege('authenticated', p.oid, 'EXECUTE') as authed
-- from pg_proc p join pg_namespace n on n.oid = p.pronamespace
-- where n.nspname = 'public' and p.proname like 'sms%' order by 1;
