-- ── DNC registry ───────────────────────────────────────────────────────────────
-- Numbers downloaded from telemarketing.donotcall.gov (free for 5 area codes), or loaded
-- from a commercial scrub. See scripts/load-dnc.mjs.
create table if not exists public.dnc_numbers (
  phone      text primary key check (phone ~ '^[0-9]{10}$'),
  loaded_at  timestamptz not null default now()
);

-- THE reason dnc_state() can ever answer "clear". A number's absence from dnc_numbers only
-- means it is unlisted if we actually hold that area code's file — otherwise absence just
-- means we never looked. Without this table a partial download silently reads as a clean
-- bill of health for the whole country, which is the exact failure that gets people sued.
create table if not exists public.dnc_area_codes (
  area_code    text primary key check (area_code ~ '^[2-9][0-9]{2}$'),
  loaded_at    timestamptz not null default now(),
