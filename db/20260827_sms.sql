-- 2026-08-27 — SMS: manual texting from the CRM.
--
-- Replaces nothing: the Railway-era sms_messages/sms_settings tables were dropped when the
-- server was decommissioned (2026-06-10). Only the contact-side scaffolding survived
-- (sms_status, last_sms_at), and this file builds on it.
--
-- Threat model for this file:
--   * The send Edge Function runs as service_role and BYPASSES RLS. So neither the tenancy
--     check nor the compliance checks can live in TypeScript — they live in
--     sms_send_precheck() below, which is the ONLY sanctioned path to a send. Same
--     precedent as phone_sync_contacts_for() in db/20260804_google_contact_sync.sql.
--   * The browser bundle ships the anon key publicly, so a guard implemented in React is
--     decoration. Nothing here trusts a client-supplied client_id, user_id, or number.
--   * Every check FAILS CLOSED. An unrecognised area code, a malformed number, or a
--     missing DNC scrub all block the send rather than allowing it.
--
-- Compliance notes (why these particular guards):
--   * 47 CFR 64.1200(c)(2) — solicitations to numbers on the National DNC Registry are
--     actionable whether sent manually or automatically. Curating the list by hand does
--     not help here, which is why dnc_state() gates the send.
--   * 47 CFR 64.1200(d) — internal DNC policy: opt-outs must be honoured promptly and
--     permanently, and must survive changing the sending number. Hence the opt-out lives
--     on the contact in our DB, not only in Twilio's per-number STOP list.
--   * Quiet hours are 8am-9pm in the RECIPIENT's local time, not the sender's.

-- SUPERSEDED IN PART by db/20260827_sms_optout_hardening.sql (same day): opt-outs moved
-- from the contact row to the number, and STOP detection gained a phrase tier. Run both.

