-- Mirrors normalizePhone() in src/lib/utils.js: digits only, last 10.
create or replace function public.sms_digits(p_phone text)
returns text
language sql immutable
as $$
  select right(regexp_replace(coalesce(p_phone, ''), '\D', '', 'g'), 10);
$;
revoke execute on function public.sms_digits(text) from public, anon;
grant execute on function public.sms_digits(text) to authenticated;

