-- true only if the instant is inside [08:00, 21:00) local in every timezone the area code
-- spans. Unknown area code → no rows → bool_and is null → coalesce false. Fails closed.
create or replace function public.sms_within_quiet_hours(p_phone text, p_at timestamptz default now())
returns boolean
language sql stable security definer set search_path = public
as $fn$
  select coalesce(bool_and(t.h >= 8 and t.h < 21), false)
  from public.area_code_timezones a
  cross join lateral (
    select extract(hour from p_at at time zone z)::int as h
    from unnest(array[a.timezone, a.alt_timezone]) as z
    where z is not null
  ) t
  where a.area_code = left(public.sms_digits(p_phone), 3);
$fn$;
revoke execute on function public.sms_within_quiet_hours(text, timestamptz) from public, anon;
grant execute on function public.sms_within_quiet_hours(text, timestamptz) to authenticated;

