-- 'listed' | 'clear' | 'unknown' | 'invalid'
create or replace function public.dnc_state(p_phone text)
returns text
language sql stable security definer set search_path = public
as $$
  select case
    when length(public.sms_digits(p_phone)) <> 10                      then 'invalid'
    when left(public.sms_digits(p_phone), 1) in ('0', '1')             then 'invalid'
    when exists (select 1 from public.dnc_numbers d
                 where d.phone = public.sms_digits(p_phone))           then 'listed'
    when exists (select 1 from public.dnc_area_codes a
                 where a.area_code = left(public.sms_digits(p_phone), 3)) then 'clear'
    else 'unknown'
  end;
$$;
revoke execute on function public.dnc_state(text) from public, anon;
grant execute on function public.dnc_state(text) to authenticated;

