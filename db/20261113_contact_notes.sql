-- Notes become their own rows (2026-11-13). Phase 1 of 2 — additive, safe to apply while
-- the previous app build is still live. Phase 2 is 20261113_contact_notes_cutover.sql.
--
-- Until now a note was an entry in property_crm_contacts.activity_log: text and a time,
-- no author, and every save rewrote the whole array. Fine for one person; in a shared
-- workspace it means anyone can overwrite or wipe a teammate's notes, and two people
-- saving at once lose one. See PLAN.md.
--
-- Rules this table enforces, in SQL because the anon key is public and a rule in React is
-- decoration:
--   * a note records who wrote it — never taken from the client
--   * members of a workspace read every note in it
--   * only the author can edit or delete, and an edit can only change the text
--   * client_id is derived from the contact, so a note cannot be filed under a workspace
--     its contact is not in
--
-- activity_log is NOT dropped. The app stops reading and writing it after cutover, which
-- leaves it as a frozen copy of the pre-migration notes until a real backup exists.

begin;

create table public.contact_notes (
  id          bigint generated by default as identity primary key,
  client_id   uuid   not null references public.clients(id) on delete cascade,
  contact_id  bigint not null references public.property_crm_contacts(id) on delete cascade,
  -- Nullable only so removing a user does not delete what they wrote.
  author_id   uuid   default auth.uid() references auth.users(id) on delete set null,
  body        text   not null check (btrim(body) <> ''),
  created_at  timestamptz not null default now(),
  edited_at   timestamptz,
  -- The id the note had inside activity_log. Makes the backfill re-runnable.
  legacy_id   text,
  unique (contact_id, legacy_id)
);

create index contact_notes_contact_idx on public.contact_notes (contact_id, created_at desc);
create index contact_notes_client_idx  on public.contact_notes (client_id, created_at desc);

-- Stamp the fields the client must not choose. client_id always comes from the contact;
-- the lookup runs as the caller, so for a contact the caller cannot see it finds nothing
-- and the NOT NULL fails the insert. author/created_at are forced whenever there is a
-- signed-in caller, and left alone otherwise so the backfill below can set them.
create function public.contact_notes_stamp()
returns trigger
language plpgsql
set search_path to ''
as $$
begin
  if tg_op = 'INSERT' then
    new.client_id := (select c.client_id from public.property_crm_contacts c where c.id = new.contact_id);
    if auth.uid() is not null then
      new.author_id  := auth.uid();
      new.created_at := now();
      new.edited_at  := null;
      new.legacy_id  := null;
    end if;
  else
    new.id         := old.id;
    new.client_id  := old.client_id;
    new.contact_id := old.contact_id;
    new.author_id  := old.author_id;
    new.created_at := old.created_at;
    new.legacy_id  := old.legacy_id;
    if new.body is distinct from old.body then new.edited_at := now(); end if;
  end if;
  return new;
end;
$$;

create trigger contact_notes_stamp
  before insert or update on public.contact_notes
  for each row execute function public.contact_notes_stamp();

alter table public.contact_notes enable row level security;

-- Policies are scoped TO authenticated, not left on the default (public, which includes
-- anon). A policy named for a role is not scoped to that role — see CLAUDE.md Tier 1.
create policy "members read notes" on public.contact_notes
  for select to authenticated
  using (client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid()));

create policy "members add their own notes" on public.contact_notes
  for insert to authenticated
  with check (
    author_id = auth.uid()
    and client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid())
  );

create policy "authors edit their own notes" on public.contact_notes
  for update to authenticated
  using (
    author_id = auth.uid()
    and client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid())
  )
  with check (
    author_id = auth.uid()
    and client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid())
  );

create policy "authors delete their own notes" on public.contact_notes
  for delete to authenticated
  using (
    author_id = auth.uid()
    and client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid())
  );

-- Supabase grants ALL on new public tables to anon and authenticated. Narrow it: anon gets
-- nothing, and authenticated can only supply the contact and the text.
revoke all on public.contact_notes from anon, authenticated;
grant select, delete on public.contact_notes to authenticated;
grant insert (contact_id, body) on public.contact_notes to authenticated;
grant update (body) on public.contact_notes to authenticated;

-- How many notes a contact has. The follow-up cadence counts notes as call attempts, and
-- the list needs that without loading every note. Maintained by a trigger from phase 2 on.
alter table public.property_crm_contacts add column note_count integer not null default 0;

-- Backfill. Same "what is a note" predicate and timestamp rule as compute_last_note_at,
-- so last_note_at means the same thing before and after. Each note is attributed to its
-- workspace's owner: every workspace has exactly one member today, so that is who wrote it.
insert into public.contact_notes (client_id, contact_id, author_id, body, created_at, legacy_id)
select c.client_id, c.id,
       (select cu.user_id from public.client_users cu
         where cu.client_id = c.client_id and cu.role = 'owner'
         order by cu.created_at limit 1),
       e->>'text',
       (coalesce(e->>'timestamp', e->>'createdAt'))::timestamptz,
       e->>'id'
from public.property_crm_contacts c,
     jsonb_array_elements(
       case when jsonb_typeof(c.activity_log) = 'array' then c.activity_log else '[]'::jsonb end
     ) as e
where (e->>'type' = 'note' or ((e->>'type' is null or e->>'type' = '') and coalesce(e->>'text', '') <> ''))
  and btrim(coalesce(e->>'text', '')) <> ''
  and coalesce(e->>'timestamp', e->>'createdAt') ~ '^\d{4}-\d{2}-\d{2}T'
on conflict (contact_id, legacy_id) do nothing;

update public.property_crm_contacts c
   set note_count = n.cnt
  from (select contact_id, count(*)::int cnt from public.contact_notes group by contact_id) n
 where n.contact_id = c.id;

commit;
