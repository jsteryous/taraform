-- Companies (2026-11-13). Additive; safe to apply before the app build that uses it.
--
-- A company is a contact of a second kind, not a separate table. It needs everything a
-- person already has — a name, phones, a status, notes with authors, follow-ups, search,
-- RLS — so it reuses property_crm_contacts with kind = 'company' and its name in
-- first_name. What is new is the link between the two: who is connected to which company.
-- A person can belong to several (an owner with three LLCs, a CPA who refers many
-- businesses), so the link is its own table.
--
-- "Who has the loan" is the company's status, since the borrower is usually the LLC and
-- not the person behind it.

begin;

alter table public.property_crm_contacts
  add column kind text not null default 'person' check (kind in ('person', 'company'));

create table public.contact_links (
  id          bigint generated by default as identity primary key,
  client_id   uuid   not null references public.clients(id) on delete cascade,
  company_id  bigint not null references public.property_crm_contacts(id) on delete cascade,
  person_id   bigint not null references public.property_crm_contacts(id) on delete cascade,
  -- The person's role at this company ("Owner", "CFO"). On the link, not the person,
  -- because it differs per company.
  title       text,
  created_by  uuid default auth.uid() references auth.users(id) on delete set null,
  created_at  timestamptz not null default now(),
  unique (company_id, person_id)
);

create index contact_links_person_idx on public.contact_links (person_id);
create index contact_links_client_idx on public.contact_links (client_id);

-- A link must join a company to a person in the SAME workspace. Checked here rather than
-- in the app: the anon key is public, and without this a member of two workspaces could
-- link a contact in one to a contact in the other and leak its name across the boundary.
-- The lookups run as the caller, so a contact they cannot see reads as missing.
create function public.contact_links_stamp()
returns trigger
language plpgsql
set search_path to ''
as $$
declare
  v_company record;
  v_person  record;
begin
  if tg_op = 'UPDATE' then
    -- Only the title can change. To re-point a link, delete it and make another.
    new.id := old.id; new.client_id := old.client_id; new.company_id := old.company_id;
    new.person_id := old.person_id; new.created_by := old.created_by; new.created_at := old.created_at;
    return new;
  end if;

  select c.client_id, c.kind into v_company from public.property_crm_contacts c where c.id = new.company_id;
  select c.client_id, c.kind into v_person  from public.property_crm_contacts c where c.id = new.person_id;
  if v_company.client_id is null or v_person.client_id is null then
    raise exception 'contact not found';
  end if;
  if v_company.kind <> 'company' or v_person.kind <> 'person' then
    raise exception 'a link joins a company to a person';
  end if;
  if v_company.client_id <> v_person.client_id then
    raise exception 'both contacts must be in the same workspace';
  end if;

  new.client_id := v_company.client_id;
  if auth.uid() is not null then
    new.created_by := auth.uid();
    new.created_at := now();
  end if;
  return new;
end;
$$;

create trigger contact_links_stamp
  before insert or update on public.contact_links
  for each row execute function public.contact_links_stamp();

alter table public.contact_links enable row level security;

-- Any member may link and unlink, the same as any member may edit a contact. Scoped TO
-- authenticated, not the default (public, which includes anon).
create policy "members manage links" on public.contact_links
  for all to authenticated
  using (client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid()))
  with check (client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid()));

revoke all on public.contact_links from anon, authenticated;
grant select, delete on public.contact_links to authenticated;
grant insert (company_id, person_id, title) on public.contact_links to authenticated;
grant update (title) on public.contact_links to authenticated;

-- Caller ID sync writes contacts into each connected user's PERSONAL Google account. A
-- banking workspace must not do that until compliance has said whether it may (PLAN.md,
-- open question), so it is excluded here by default rather than left to someone
-- remembering to disconnect. Same signature, so CREATE OR REPLACE keeps the grants
-- (postgres, service_role only).
create or replace function public.phone_sync_contacts_for(p_user uuid)
returns table(id bigint, client_id uuid, first_name text, last_name text, phones jsonb, bad_phones jsonb, county text, status text, tax_map_ids jsonb, acreage text)
language sql
security definer
set search_path to 'public'
as $$
  select c.id, c.client_id, c.first_name, c.last_name,
         c.phones, c.bad_phones, c.county, c.status,
         c.tax_map_ids, c.acreage
  from public.property_crm_contacts c
  where c.has_good_phone
    and c.client_id in (
      select cu.client_id from public.client_users cu where cu.user_id = p_user
    )
    and not exists (
      select 1 from public.clients cl
       where cl.id = c.client_id and cl.config->>'type' = 'banking'
    )
  order by c.id;
$$;

commit;
