-- ---------------------------------------------------------------------------------------
-- Fix: the existing stamp triggers blocked deleting a user
-- ---------------------------------------------------------------------------------------

-- contact_notes.author_id and contact_links.created_by are ON DELETE SET NULL, and their
-- BEFORE UPDATE triggers froze them to the old value. SET NULL is carried out as an
-- UPDATE that fires those triggers, so the freeze put the deleted user's id back and the
-- foreign key failed: deleting any auth user who had written a note or made a link
-- errored. (Reproduced 2026-11-18 on a scratch table.) Both now let that column go to
-- NULL and nothing else. Same signatures, so CREATE OR REPLACE keeps the grants.

create or replace function public.contact_notes_stamp()
returns trigger
language plpgsql
set search_path to ''
as $$
begin
  if tg_op = 'INSERT' then
    new.client_id := (select c.client_id from public.property_crm_contacts c where c.id = new.contact_id);
    if auth.uid() is not null then
      new.author_id  := auth.uid();
      new.created_at := now();
      new.edited_at  := null;
      new.legacy_id  := null;
    end if;
  else
    new.id         := old.id;
    new.client_id  := old.client_id;
    new.contact_id := old.contact_id;
    if new.author_id is not null then new.author_id := old.author_id; end if;
    new.created_at := old.created_at;
    new.legacy_id  := old.legacy_id;
    if new.body is distinct from old.body then new.edited_at := now(); end if;
  end if;
  return new;
end;
$$;

create or replace function public.contact_links_stamp()
returns trigger
language plpgsql
set search_path to ''
as $$
declare
  v_company record;
  v_person  record;
begin
  if tg_op = 'UPDATE' then
    -- Only the title can change. To re-point a link, delete it and make another.
    new.id := old.id; new.client_id := old.client_id; new.company_id := old.company_id;
    new.person_id := old.person_id; new.created_at := old.created_at;
    if new.created_by is not null then new.created_by := old.created_by; end if;
    return new;
  end if;

  select c.client_id, c.kind into v_company from public.property_crm_contacts c where c.id = new.company_id;
  select c.client_id, c.kind into v_person  from public.property_crm_contacts c where c.id = new.person_id;
  if v_company.client_id is null or v_person.client_id is null then
    raise exception 'contact not found';
  end if;
  if v_company.kind <> 'company' or v_person.kind <> 'person' then
    raise exception 'a link joins a company to a person';
  end if;
  if v_company.client_id <> v_person.client_id then
    raise exception 'both contacts must be in the same workspace';
  end if;

  new.client_id := v_company.client_id;
  if auth.uid() is not null then
    new.created_by := auth.uid();
    new.created_at := now();
  end if;
  return new;
end;
$$;

