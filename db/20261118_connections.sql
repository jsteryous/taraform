-- ---------------------------------------------------------------------------------------
-- contact_group_members
-- ---------------------------------------------------------------------------------------

-- Exactly one of contact_id (a contact in the group) or user_id (a teammate, from "Your
-- groups"). Add and remove only; there is nothing to edit.
create table public.contact_group_members (
  id             bigint generated by default as identity primary key,
  client_id      uuid   not null references public.clients(id) on delete cascade,
  group_id       bigint not null references public.contact_groups(id) on delete cascade,
  contact_id     bigint references public.property_crm_contacts(id) on delete cascade,
  user_id        uuid   references auth.users(id) on delete cascade,
  source_note_id bigint references public.contact_notes(id) on delete set null,
  created_by     uuid default auth.uid() references auth.users(id) on delete set null,
  created_at     timestamptz not null default now(),
  check (num_nonnulls(contact_id, user_id) = 1),
  unique (group_id, contact_id),
  unique (group_id, user_id)
);

create index contact_group_members_contact_idx on public.contact_group_members (contact_id);
create index contact_group_members_user_idx    on public.contact_group_members (user_id);
create index contact_group_members_client_idx  on public.contact_group_members (client_id);

create function public.contact_group_members_stamp()
returns trigger
language plpgsql
set search_path to ''
as $$
declare
  v_group  uuid;
  v_ws     uuid;
  v_note   record;
begin
  if tg_op = 'UPDATE' then
    -- No column is granted for UPDATE; this only runs for ON DELETE SET NULL, which may
    -- clear source_note_id or created_by and nothing else.
    new.id := old.id; new.client_id := old.client_id; new.group_id := old.group_id;
    new.contact_id := old.contact_id; new.user_id := old.user_id; new.created_at := old.created_at;
    if new.source_note_id is not null then new.source_note_id := old.source_note_id; end if;
    if new.created_by is not null then new.created_by := old.created_by; end if;
    return new;
  end if;

  select g.client_id into v_group from public.contact_groups g where g.id = new.group_id;
  if v_group is null then
    raise exception 'group not found';
  end if;

  if new.contact_id is not null then
    select c.client_id into v_ws from public.property_crm_contacts c where c.id = new.contact_id;
    if v_ws is null then
      raise exception 'contact not found';
    end if;
    if v_ws <> v_group then
      raise exception 'the contact and the group must be in the same workspace';
    end if;
  else
    -- A teammate must belong to the workspace. This lookup runs as the caller, and a
    -- member can see only their own client_users row, so from the app it also refuses
    -- adding anyone but yourself (proven: it fires before the insert policy, which
    -- requires user_id = auth.uid() as well).
    if not exists (select 1 from public.client_users cu
                    where cu.client_id = v_group and cu.user_id = new.user_id) then
      raise exception 'that user is not a member of this workspace';
    end if;
  end if;

  if new.source_note_id is not null then
    select n.client_id, n.contact_id into v_note from public.contact_notes n where n.id = new.source_note_id;
    if v_note.client_id is null then
      raise exception 'note not found';
    end if;
    if new.contact_id is null or v_note.contact_id <> new.contact_id then
      raise exception 'the source note must be on the contact being added';
    end if;
  end if;

  new.client_id := v_group;
  if auth.uid() is not null then
    new.created_by := auth.uid();
    new.created_at := now();
  end if;
  return new;
end;
$$;

create trigger contact_group_members_stamp
  before insert or update on public.contact_group_members
  for each row execute function public.contact_group_members_stamp();

alter table public.contact_group_members enable row level security;

create policy "members read group members" on public.contact_group_members
  for select to authenticated
  using (client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid()));

-- Any member may put a contact in a group; a teammate row may only be one's own.
create policy "members add group members" on public.contact_group_members
  for insert to authenticated
  with check (
    (user_id is null or user_id = auth.uid())
    and client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid())
  );

create policy "members remove group members" on public.contact_group_members
  for delete to authenticated
  using (
    (user_id is null or user_id = auth.uid())
    and client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid())
  );

revoke all on public.contact_group_members from anon, authenticated;
grant select, delete on public.contact_group_members to authenticated;
grant insert (group_id, contact_id, user_id, source_note_id) on public.contact_group_members to authenticated;

-- ---------------------------------------------------------------------------------------
-- finder_ignored
-- ---------------------------------------------------------------------------------------

-- Words the note finder stops offering ("LinkedIn", "Monday"), per workspace. Stored
-- lowercased and trimmed. Insert with ON CONFLICT DO NOTHING; no update.
create table public.finder_ignored (
  client_id  uuid not null references public.clients(id) on delete cascade,
  term       text not null check (term <> '' and length(term) <= 120),
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  primary key (client_id, term)
);

create function public.finder_ignored_stamp()
returns trigger
language plpgsql
set search_path to ''
as $$
begin
  if tg_op = 'UPDATE' then
    -- Only ON DELETE SET NULL on created_by gets here.
    new.client_id := old.client_id; new.term := old.term; new.created_at := old.created_at;
    if new.created_by is not null then new.created_by := old.created_by; end if;
    return new;
  end if;
  new.term := lower(btrim(new.term));
  if auth.uid() is not null then
    new.created_by := auth.uid();
    new.created_at := now();
  end if;
  return new;
end;
$$;

create trigger finder_ignored_stamp
  before insert or update on public.finder_ignored
  for each row execute function public.finder_ignored_stamp();

alter table public.finder_ignored enable row level security;

create policy "members manage ignored terms" on public.finder_ignored
  for all to authenticated
  using (client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid()))
  with check (client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid()));

revoke all on public.finder_ignored from anon, authenticated;
grant select, delete on public.finder_ignored to authenticated;
grant insert (client_id, term) on public.finder_ignored to authenticated;

-- ---------------------------------------------------------------------------------------
-- Leaving a workspace takes your familiarity and "Your groups" with you
-- ---------------------------------------------------------------------------------------

-- Members can read only their own client_users row, so contact_ways_in (SECURITY
-- INVOKER) cannot filter out people who have left. Without this, "Ask Kim, she knows
-- him well" would outlive Kim's membership. Connections, groups and contact members are
-- shared facts and stay.
create function public.client_users_leave_cleanup()
returns trigger
language plpgsql
security definer
set search_path to ''
as $$
begin
  delete from public.contact_familiarity f
   where f.client_id = old.client_id and f.user_id = old.user_id;
  delete from public.contact_group_members m
   where m.client_id = old.client_id and m.user_id = old.user_id;
  return old;
end;
$$;

revoke all on function public.client_users_leave_cleanup() from public, anon, authenticated;

create trigger client_users_leave_cleanup
  after delete on public.client_users
  for each row execute function public.client_users_leave_cleanup();

-- ---------------------------------------------------------------------------------------
-- contact_ways_in: one read for the Connections & Ways In column
-- ---------------------------------------------------------------------------------------

-- SECURITY INVOKER: every table read here is under the caller's RLS, so it cannot show
-- more than the caller could select themselves. Returns NULL for a contact the caller
-- cannot see.
--
-- Warmth (PLAN.md):
--   warm    a teammate knows them (know / know_well)
--   intro   they are connected to someone a teammate knows
--   common  they share a group with a teammate, or with someone a teammate knows, or a
--           teammate has met them
--   cold    none of the above
-- Shape:
--   { warmth, familiarity: [{user_id, level, updated_at}],
--     connections: [{id, contact_id, first_name, last_name, description, referred_by,
--                    unsure, source_note_id, note_body, created_by, created_at,
--                    known_by: [{user_id, level}]}],   -- warmest first
--     groups: [{id, name, kind, source_note_id, teammates: [user_id],
--               known_contacts: [{contact_id, first_name, last_name,
--                                 known_by: [{user_id, level}]}]}] }
create function public.contact_ways_in(p_contact_id bigint)
returns jsonb
language sql
stable
security invoker
set search_path to ''
as $$
  with
  fam as (
    select f.user_id, f.level, f.updated_at
      from public.contact_familiarity f
     where f.contact_id = p_contact_id
  ),
  conn as (
    select cc.id,
           case when cc.a_id = p_contact_id then cc.b_id else cc.a_id end as other_id,
           cc.description, cc.referred_by, cc.unsure, cc.source_note_id,
           cc.created_by, cc.created_at
      from public.contact_connections cc
     where cc.a_id = p_contact_id or cc.b_id = p_contact_id
  ),
  conn_full as (
    select c.*, o.first_name, o.last_name, n.body as note_body,
           k.known_by, coalesce(k.best, 0) as best
      from conn c
      join public.property_crm_contacts o on o.id = c.other_id
      left join public.contact_notes n on n.id = c.source_note_id
      left join lateral (
        select jsonb_agg(jsonb_build_object('user_id', f.user_id, 'level', f.level)
                         order by case f.level when 'know_well' then 3 when 'know' then 2 else 1 end desc, f.user_id) as known_by,
               max(case f.level when 'know_well' then 3 when 'know' then 2 else 1 end) as best
          from public.contact_familiarity f
         where f.contact_id = c.other_id
      ) k on true
  ),
  grp as (
    select g.id, g.name, g.kind, m.source_note_id
      from public.contact_group_members m
      join public.contact_groups g on g.id = m.group_id
     where m.contact_id = p_contact_id
  ),
  grp_full as (
    select g.*,
           coalesce((select jsonb_agg(t.user_id order by t.created_at)
                       from public.contact_group_members t
                      where t.group_id = g.id and t.user_id is not null), '[]'::jsonb) as teammates,
           coalesce((select jsonb_agg(jsonb_build_object(
                              'contact_id', o.id, 'first_name', o.first_name,
                              'last_name', o.last_name, 'known_by', k.known_by)
                            order by o.last_name, o.first_name)
                       from public.contact_group_members cm
                       join public.property_crm_contacts o on o.id = cm.contact_id
                       join lateral (
                         select jsonb_agg(jsonb_build_object('user_id', f.user_id, 'level', f.level)
                                          order by case f.level when 'know_well' then 3 when 'know' then 2 else 1 end desc) as known_by
                           from public.contact_familiarity f
                          where f.contact_id = o.id and f.level in ('know', 'know_well')
                       ) k on k.known_by is not null
                      where cm.group_id = g.id and cm.contact_id <> p_contact_id), '[]'::jsonb) as known_contacts
      from grp g
  )
  select jsonb_build_object(
    'warmth', case
      when exists (select 1 from fam where level in ('know', 'know_well')) then 'warm'
      when exists (select 1 from conn_full where best >= 2) then 'intro'
      when exists (select 1 from fam where level = 'met')
        or exists (select 1 from grp_full
                    where teammates <> '[]'::jsonb or known_contacts <> '[]'::jsonb) then 'common'
      else 'cold' end,
    'familiarity', coalesce((select jsonb_agg(jsonb_build_object(
                     'user_id', user_id, 'level', level, 'updated_at', updated_at)
                     order by case level when 'know_well' then 3 when 'know' then 2 else 1 end desc, updated_at) from fam), '[]'::jsonb),
    'connections', coalesce((select jsonb_agg(jsonb_build_object(
                     'id', id, 'contact_id', other_id, 'first_name', first_name,
                     'last_name', last_name, 'description', description,
                     'referred_by', referred_by, 'unsure', unsure,
                     'source_note_id', source_note_id, 'note_body', note_body,
                     'created_by', created_by, 'created_at', created_at,
                     'known_by', coalesce(known_by, '[]'::jsonb))
                     order by best desc, unsure, created_at) from conn_full), '[]'::jsonb),
    'groups', coalesce((select jsonb_agg(jsonb_build_object(
                'id', id, 'name', name, 'kind', kind, 'source_note_id', source_note_id,
                'teammates', teammates, 'known_contacts', known_contacts)
                order by jsonb_array_length(teammates) + jsonb_array_length(known_contacts) desc, name)
                from grp_full), '[]'::jsonb)
  )
  where exists (select 1 from public.property_crm_contacts c where c.id = p_contact_id);
$$;

revoke all on function public.contact_ways_in(bigint) from public, anon;
