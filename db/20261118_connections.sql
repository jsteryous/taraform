-- Connections & Ways In, step 1: the database (2026-11-18). Additive; safe to apply
-- before any app build uses it. Design: PLAN.md, "Next: Connections & Ways In".
--
-- Five tables and two functions:
--   contact_connections    person <-> person, a shared fact any member may edit
--   contact_familiarity    how well *I* know a contact; each user writes only their own
--   contact_groups         clubs, schools, boards, interests (with other names)
--   contact_group_members  a contact in a group, or a teammate in "Your groups"
--   finder_ignored         words the note finder should stop offering
--   set_familiarity()      upsert/clear the caller's own familiarity row
--   contact_ways_in()      one read for the column: warmth, connections, common ground
--
-- Same rules as contact_notes / contact_links, in SQL because the anon key is public:
--   * client_id is derived (from the contact or group), never trusted from the client.
--     The one exception is the two tables with nothing to derive it from (contact_groups,
--     finder_ignored): there the client names the workspace and the policy requires the
--     caller to be a member of it.
--   * everything a row references must be in that same workspace. Lookups run as the
--     caller, so a row they cannot see reads as missing.
--   * policies TO authenticated (never the default, public, which includes anon), gated
--     on client_users; revoke all from anon/authenticated, then column-level grants.
--   * who and when (created_by, user_id, timestamps) are forced by the trigger.
--
-- Also fixes a latent bug in the two existing stamp triggers (end of file).

begin;

-- ---------------------------------------------------------------------------------------
-- contact_connections
-- ---------------------------------------------------------------------------------------

create table public.contact_connections (
  id             bigint generated by default as identity primary key,
  client_id      uuid   not null references public.clients(id) on delete cascade,
  -- Stored with a_id < b_id so each pair exists once. The trigger sorts them, so the app
  -- can send either order.
  a_id           bigint not null references public.property_crm_contacts(id) on delete cascade,
  b_id           bigint not null references public.property_crm_contacts(id) on delete cascade,
  description    text check (description is null or length(description) <= 500),
  -- The only direction a connection has: which of the two did the referring.
  referred_by    bigint,
  -- "I think so, but I'm not sure yet."
  unsure         boolean not null default false,
  -- The note it was found in, quoted as the reason. Deleting the note keeps the link.
  source_note_id bigint references public.contact_notes(id) on delete set null,
  created_by     uuid default auth.uid() references auth.users(id) on delete set null,
  created_at     timestamptz not null default now(),
  check (a_id < b_id),
  check (referred_by is null or referred_by = a_id or referred_by = b_id),
  unique (a_id, b_id)
);

create index contact_connections_b_idx      on public.contact_connections (b_id);
create index contact_connections_client_idx on public.contact_connections (client_id);

create function public.contact_connections_stamp()
returns trigger
language plpgsql
set search_path to ''
as $$
declare
  v_a record;
  v_b record;
  v_note record;
  v_tmp bigint;
begin
  if tg_op = 'UPDATE' then
    -- Only description, referred_by and unsure change. To re-point, delete and re-add.
    new.id := old.id; new.client_id := old.client_id; new.a_id := old.a_id; new.b_id := old.b_id;
    new.created_at := old.created_at;
    -- These two may become NULL and nothing else (ON DELETE SET NULL runs as an UPDATE
    -- and fires this trigger; freezing them would make deleting the note or user fail).
    if new.source_note_id is not null then new.source_note_id := old.source_note_id; end if;
    if new.created_by is not null then new.created_by := old.created_by; end if;
    return new;
  end if;

  if new.a_id = new.b_id then
    raise exception 'a contact cannot be connected to itself';
  end if;
  if new.a_id > new.b_id then
    v_tmp := new.a_id; new.a_id := new.b_id; new.b_id := v_tmp;
  end if;

  select c.client_id, c.kind into v_a from public.property_crm_contacts c where c.id = new.a_id;
  select c.client_id, c.kind into v_b from public.property_crm_contacts c where c.id = new.b_id;
  if v_a.client_id is null or v_b.client_id is null then
    raise exception 'contact not found';
  end if;
  if v_a.kind <> 'person' or v_b.kind <> 'person' then
    raise exception 'a connection joins two people (use a company link for a company)';
  end if;
  if v_a.client_id <> v_b.client_id then
    raise exception 'both contacts must be in the same workspace';
  end if;

  if new.source_note_id is not null then
    select n.client_id, n.contact_id into v_note from public.contact_notes n where n.id = new.source_note_id;
    if v_note.client_id is null then
      raise exception 'note not found';
    end if;
    if v_note.contact_id <> new.a_id and v_note.contact_id <> new.b_id then
      raise exception 'the source note must be on one of the two contacts';
    end if;
  end if;

  new.client_id := v_a.client_id;
  if auth.uid() is not null then
    new.created_by := auth.uid();
    new.created_at := now();
  end if;
  return new;
end;
$$;

create trigger contact_connections_stamp
  before insert or update on public.contact_connections
  for each row execute function public.contact_connections_stamp();

alter table public.contact_connections enable row level security;

-- A shared fact, like a company link: any member may add, edit or remove one.
create policy "members manage connections" on public.contact_connections
  for all to authenticated
  using (client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid()))
  with check (client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid()));

revoke all on public.contact_connections from anon, authenticated;
grant select, delete on public.contact_connections to authenticated;
grant insert (a_id, b_id, description, referred_by, unsure, source_note_id) on public.contact_connections to authenticated;
grant update (description, referred_by, unsure) on public.contact_connections to authenticated;

-- ---------------------------------------------------------------------------------------
-- contact_familiarity
-- ---------------------------------------------------------------------------------------

-- "Haven't met" is the absence of a row. Entered, never computed: a note count says
-- nothing about a relationship (fifteen notes can be fifteen unanswered voicemails).
create table public.contact_familiarity (
  client_id  uuid   not null references public.clients(id) on delete cascade,
  contact_id bigint not null references public.property_crm_contacts(id) on delete cascade,
  -- Cascade, not set null: a familiarity with no one behind it means nothing.
  user_id    uuid   not null default auth.uid() references auth.users(id) on delete cascade,
  level      text   not null check (level in ('met', 'know', 'know_well')),
  updated_at timestamptz not null default now(),
  primary key (contact_id, user_id)
);

create index contact_familiarity_client_idx on public.contact_familiarity (client_id);
create index contact_familiarity_user_idx   on public.contact_familiarity (user_id);

create function public.contact_familiarity_stamp()
returns trigger
language plpgsql
set search_path to ''
as $$
declare
  v_c record;
begin
  if tg_op = 'UPDATE' then
    new.client_id := old.client_id; new.contact_id := old.contact_id; new.user_id := old.user_id;
    new.updated_at := now();
    return new;
  end if;

  select c.client_id, c.kind into v_c from public.property_crm_contacts c where c.id = new.contact_id;
  if v_c.client_id is null then
    raise exception 'contact not found';
  end if;
  if v_c.kind <> 'person' then
    raise exception 'familiarity is with a person, not a company';
  end if;
  new.client_id := v_c.client_id;
  if auth.uid() is not null then
    new.user_id := auth.uid();
  end if;
  new.updated_at := now();
  return new;
end;
$$;

create trigger contact_familiarity_stamp
  before insert or update on public.contact_familiarity
  for each row execute function public.contact_familiarity_stamp();

alter table public.contact_familiarity enable row level security;

create policy "members read familiarity" on public.contact_familiarity
  for select to authenticated
  using (client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid()));

create policy "users add their own familiarity" on public.contact_familiarity
  for insert to authenticated
  with check (
    user_id = auth.uid()
    and client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid())
  );

create policy "users change their own familiarity" on public.contact_familiarity
  for update to authenticated
  using (
    user_id = auth.uid()
    and client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid())
  )
  with check (
    user_id = auth.uid()
    and client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid())
  );

create policy "users remove their own familiarity" on public.contact_familiarity
  for delete to authenticated
  using (
    user_id = auth.uid()
    and client_id in (select cu.client_id from public.client_users cu where cu.user_id = auth.uid())
  );

revoke all on public.contact_familiarity from anon, authenticated;
grant select, delete on public.contact_familiarity to authenticated;
grant insert (contact_id, level) on public.contact_familiarity to authenticated;
grant update (level) on public.contact_familiarity to authenticated;

-- The app's one write path. A PostgREST upsert would need UPDATE on contact_id (it sets
-- every inserted column on conflict); this needs only UPDATE (level). NULL level clears
-- the row ("Haven't met"). SECURITY INVOKER, so the policies above still decide.
create function public.set_familiarity(p_contact_id bigint, p_level text)
returns void
language plpgsql
security invoker
set search_path to ''
as $$
begin
  if p_level is null then
    delete from public.contact_familiarity f
     where f.contact_id = p_contact_id and f.user_id = auth.uid();
  else
    insert into public.contact_familiarity (contact_id, level)
    values (p_contact_id, p_level)
    on conflict (contact_id, user_id) do update set level = excluded.level;
  end if;
end;
$$;

revoke all on function public.set_familiarity(bigint, text) from public, anon;
grant execute on function public.set_familiarity(bigint, text) to authenticated;

-- ---------------------------------------------------------------------------------------
-- contact_groups
-- ---------------------------------------------------------------------------------------

create table public.contact_groups (
  id         bigint generated by default as identity primary key,
  client_id  uuid   not null references public.clients(id) on delete cascade,
  name       text   not null check (btrim(name) <> '' and length(name) <= 120),
  -- Other names the finder should match ("GCC" for the full club name). Not unique
  -- across groups: an alias that matches two groups makes the finder ask, the same as a
  -- name that matches two contacts.
  aliases    text[] not null default '{}',
  kind       text   not null default 'other'
             check (kind in ('club', 'school', 'faith', 'interest', 'other')),
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create unique index contact_groups_name_uq on public.contact_groups (client_id, lower(name));

create function public.contact_groups_stamp()
returns trigger
language plpgsql
set search_path to ''
as $$
begin
  if tg_op = 'UPDATE' then
    new.id := old.id; new.client_id := old.client_id; new.created_at := old.created_at;
    if new.created_by is not null then new.created_by := old.created_by; end if;
  elsif auth.uid() is not null then
    new.created_by := auth.uid();
    new.created_at := now();
  end if;

  new.name := btrim(new.name);
  new.aliases := coalesce(array(
    select distinct btrim(a) from unnest(new.aliases) a
     where btrim(a) <> '' and lower(btrim(a)) <> lower(new.name)
     order by 1
  ), '{}');

  -- Faith groups stay off in banking workspaces until compliance answers (PLAN.md,
  -- questions for compliance: ECOA / Reg B bar religion in credit decisions). Enforced
  -- here, not only hidden in the UI, so no path into a bank workspace can record one.
  if new.kind = 'faith' and exists (
       select 1 from public.clients cl
        where cl.id = new.client_id and cl.config->>'type' = 'banking') then
    raise exception 'faith groups are not available in a banking workspace';
  end if;
  return new;
end;
$$;

create trigger contact_groups_stamp
  before insert or update on public.contact_groups
  for each row execute function public.contact_groups_stamp();

alter table public.contact_groups enable row level security;

